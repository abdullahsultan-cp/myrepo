"""paths.py — every path the Pages build reads or writes, in one place.

This exists for the same reason `pipeline/paths_root.py` does. Before it, each
script recomputed its own paths from `__file__` and dropped its output next to
the inputs, so Pages-Pipeline/ was one flat folder of 14 files where 11 were
generated and nobody could tell which. Worse, `join.py` reached into the news
taxonomy with a hand-built `../data/taxonomy/...` that broke silently the day
the repo grew a folder per content type -- the file simply was not there, and
only the enrichment it fed went quiet.

The shape:

    data/     the three real inputs. Tracked, and the only things a human supplies.
    out/      deliverables — the CSVs and HTML handed to AKU. Tracked.
    out/work/ intermediates the steps pass between themselves. Gitignored.
    build/    this code, plus assets/ for what the rendered pages inline.

If a script needs a new file, name it here rather than joining a path inline.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAGES = os.path.dirname(HERE)
ROOT = os.path.dirname(PAGES)

DATA = os.path.join(PAGES, "data")
OUT = os.path.join(PAGES, "out")
WORK = os.path.join(OUT, "work")
ASSETS = os.path.join(HERE, "assets")
PORTAL = os.path.join(PAGES, "portal")

for _d in (DATA, OUT, WORK):
    os.makedirs(_d, exist_ok=True)

# ---------------------------------------------------------------- the inputs
# The SharePoint permissions export: 612 webs, their titles, owner groups and AD
# domains. The name is AKU's own and is kept verbatim so it can be matched
# against what they send next time.
PERMISSIONS_CSV = os.path.join(
    DATA, "AKU - User - Permissions - Sites - Groups - "
          "SharePoint_2016_User_Roles_Mapping.csv")

# The only page-level inventory that exists: 3,340 live page URLs.
PAGES_HTM = os.path.join(DATA, "AKU-EN_1.HTM")

# AKU's own list of what to migrate. Authoritative where it disagrees with the
# other two.
VISIBLE_PAGES_CSV = os.path.join(DATA, "aku-university-visible-pages.csv")


def data(name):
    """An input file by name."""
    return os.path.join(DATA, name)


def out(name):
    """A deliverable — tracked, and handed to AKU."""
    return os.path.join(OUT, name)


def work(name):
    """An intermediate — gitignored, regenerated by re-running the step."""
    return os.path.join(WORK, name)


def asset(name):
    """Something the rendered HTML inlines, e.g. portal.css."""
    return os.path.join(ASSETS, name)


def taxonomy_seed():
    """The news taxonomy's region/entity/department tree.

    Pages borrows it to name the regions and entities a section belongs to, so
    the two migrations agree on spelling. Resolved through paths_root rather
    than by walking up from __file__: this path moved once already, when the
    repo grew a folder per content type, and the hand-built version broke
    without saying so.
    """
    sys.path.insert(0, os.path.join(ROOT, "pipeline"))
    from paths_root import P
    P.use("news")
    return os.path.join(P.SEED, "regions_entities_departments.json")
