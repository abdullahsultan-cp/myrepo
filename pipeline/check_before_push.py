#!/usr/bin/env python3
"""check_before_push.py — did you change something that is not yours?

Two people work in this repo on different content types. This reads `git
status` and says whether anything staged or modified falls outside the folder
you own, so the answer arrives before the push rather than as a conflict.

    python pipeline/check_before_push.py --type blogs
    python pipeline/check_before_push.py --type events --strict

Advisory by default: it prints and exits 0. `--strict` exits 1 instead, for a
pre-push hook.

It cannot know intent. A shared change may be exactly right -- blogs needed one
-- so this asks a question rather than refusing. See CONTRIBUTING.md.
"""

import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _bootstrap

_bootstrap.ensure()

from paths_root import ROOT, TYPES, P

# Shared, and able to break the other person's work. Ordered worst first.
SHARED = [
    ("pipeline/", "the base every type inherits — can break the other type"),
    ("config/types/_TEMPLATE.json", "the boilerplate every new type copies"),
    ("tests/", "shared"),
    (".gitignore", "shared"),
    (".gitattributes", "shared"),
    ("requirements.txt", "shared"),
    ("CLAUDE.md", "shared docs"),
    ("README.md", "shared docs"),
    ("CONTRIBUTING.md", "shared docs"),
    ("RUN_MIGRATION.md", "shared docs"),
    ("docs/", "shared docs"),
]

# Regenerated by running something. Usually not an intended change.
REGENERATED = [
    ("storyblok_space/", "a snapshot of the front-end dev's space — re-fetch, do not merge"),
    ("storyblok-viewer/src/constants/", "written by extract-viewer-filters"),
]

NEVER = ["config/storyblok.json", "config/database.json"]


def _run(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                          text=True, encoding="utf-8")


def changed(pushed=False):
    """What to judge: the working tree, or what is about to be pushed.

    `pushed=True` looks at the COMMITS between the upstream and HEAD, which is
    the only correct question for a pre-push hook. It used to read
    `git status --porcelain` in both cases, so the hook blocked a push because
    of files somebody had open and uncommitted — none of which were going
    anywhere. A guard that fires on things you are not doing gets switched off,
    and then it is not guarding anything.

    Falls back to the working tree when there is no upstream yet, which is the
    right answer for a first push and for the manual `check_before_push.py`.
    """
    if pushed:
        upstream = _run("rev-parse", "--abbrev-ref", "--symbolic-full-name",
                        "@{u}")
        if upstream.returncode == 0 and upstream.stdout.strip():
            out = _run("diff", "--name-status",
                       f"{upstream.stdout.strip()}...HEAD").stdout
            rows = []
            for line in out.splitlines():
                if not line.strip():
                    continue
                parts = line.split("\t")
                path = parts[-1].strip().strip('"')
                rows.append((parts[0][:2].ljust(2),
                             path.replace("\\", "/")))
            return rows

    out = _run("status", "--porcelain").stdout
    rows = []
    for line in out.splitlines():
        if not line.strip():
            continue
        path = line[3:].strip().strip('"')
        if " -> " in path:                    # a rename
            path = path.split(" -> ", 1)[1]
        rows.append((line[:2], path.replace("\\", "/")))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--type", choices=sorted(TYPES), default=None)
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 when something is outside your folder")
    a = ap.parse_args()
    mine = a.type or P.type
    P.use(mine)
    own = os.path.basename(P.PIPELINE) + "/"
    own_profile = f"config/types/{mine}.json"

    # A pre-push run (--strict) judges the COMMITS being pushed; a manual run
    # judges the working tree, which is what you want while still editing.
    rows = changed(pushed=a.strict)
    if not rows:
        print("  nothing changed")
        return 0

    yours, shared, regen, other_type, secrets = [], [], [], [], []
    for st, path in rows:
        if any(path == n for n in NEVER):
            secrets.append(path); continue
        if path.startswith(own) or path == own_profile:
            yours.append(path); continue
        hit = next((why for pre, why in REGENERATED if path.startswith(pre)), None)
        if hit:
            regen.append((path, hit)); continue
        hit = next((why for pre, why in SHARED if path.startswith(pre) or path == pre), None)
        if hit:
            shared.append((path, hit)); continue
        t = next((t for t in TYPES if t != mine
                  and path.startswith(TYPES[t]["folder"] + "/")), None)
        if t:
            other_type.append((path, t)); continue
        shared.append((path, "outside any type folder"))

    print(f"\n  you are working on: {mine}   ({own})")
    print(f"  {len(rows)} changed path(s)\n")
    print(f"  yours                 {len(yours)}")
    if yours:
        for p in yours[:6]:
            print(f"      {p}")
        if len(yours) > 6:
            print(f"      ... {len(yours) - 6} more")

    problems = 0
    if secrets:
        problems += len(secrets)
        print(f"\n  SECRETS — never commit these ({len(secrets)})")
        for p in secrets:
            print(f"      {p}")

    if other_type:
        problems += len(other_type)
        print(f"\n  ANOTHER CONTENT TYPE'S FOLDER ({len(other_type)})")
        print("    Almost always a command run with the wrong --type.")
        for p, t in other_type:
            print(f"      {p}   ({t})")
        print(f"    git checkout -- <path>   then re-run with --type {mine}")

    if regen:
        print(f"\n  REGENERATED, probably not an intended change ({len(regen)})")
        for p, why in regen[:8]:
            print(f"      {p}\n          {why}")
        print("    git checkout -- <path>   if you only re-ran something")

    if shared:
        print(f"\n  SHARED ({len(shared)}) — fine if deliberate, but tell the other person")
        for p, why in shared[:10]:
            print(f"      {p:<44}{why}")
        print(f"    If this is to make {mine} work, check CONTRIBUTING.md section 3 first:")
        print("    skip_steps / extra_steps / a hook / your profile usually does it.")

    if not (problems or shared or regen):
        print("\n  everything is inside your own folder — push away")
    print()
    return 1 if (a.strict and (problems or shared)) else 0


if __name__ == "__main__":
    sys.exit(main())
