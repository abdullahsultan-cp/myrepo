"""Classify storyblok_stories by thumbnail, GIF, and video media properties."""

from json import dump, dumps, load
from os import listdir, makedirs
from os.path import abspath, dirname, isfile, join

MEDIA_FILTER_DEFINITIONS = {
    "thumbnail": {
        "label": "Thumbnail image",
        "description": (
            "Story has a Metadata.csv 'Thumbnail image' asset injected as a "
            "news_media blok with role 'thumbnail' (listing preview, separate from banner/medium)."
        ),
    },
    "gif": {
        "label": "GIF",
        "description": (
            "Story has at least one GIF in content.media (usually banner or medium) "
            "or a GIF reference in rich text."
        ),
    },
    "video_file": {
        "label": "Video file",
        "description": (
            "Story has a downloadable video file in content.media from Metadata.csv "
            "Video1/Video2/Video3 (mp4, mov, etc.)."
        ),
    },
    "video_embed": {
        "label": "Embedded video",
        "description": (
            "Story body contains an embedded video blok (YouTube or iframe), "
            "not a hosted media file."
        ),
    },
}


def classify_story_media(story, story_filename):
    content = story.get("content") or {}
    story_id = str(
        (story.get("meta_data") or {}).get("sharepoint_id")
        or content.get("sharepoint_id")
        or story_filename[:-5]
    )
    title = content.get("title") or story.get("name") or ""
    slug = story.get("slug") or ""

    flags = {key: False for key in MEDIA_FILTER_DEFINITIONS}
    media_items = []
    body = content.get("body") or {}
    body_json = dumps(body) if body else ""

    for blok in content.get("media") or []:
        if not isinstance(blok, dict):
            continue
        role = blok.get("role")
        media_type = blok.get("media_type")
        filename = blok.get("filename")
        item = {
            "role": role,
            "media_type": media_type,
            "filename": filename,
            "src": blok.get("src"),
        }
        media_items.append(item)

        if role == "thumbnail":
            flags["thumbnail"] = True
        if media_type == "gif":
            flags["gif"] = True
        if media_type == "video":
            flags["video_file"] = True

    if "video_embed" in body_json:
        flags["video_embed"] = True

    if not flags["gif"] and (
        '"media_type": "gif"' in body_json
        or ".gif" in body_json.lower()
    ):
        flags["gif"] = True

    active_filters = [key for key, enabled in flags.items() if enabled]
    return {
        "story_id": story_id,
        "story_file": story_filename,
        "title": title,
        "slug": slug,
        "sequence_number": content.get("sequence_number"),
        "flags": flags,
        "filters": active_filters,
        "media_items": media_items,
    }


def build_classification_report(stories_dir):
    story_files = sorted(
        filename for filename in listdir(stories_dir) if filename.endswith(".json")
    )

    stories = []
    buckets = {key: [] for key in MEDIA_FILTER_DEFINITIONS}
    filter_counts = {key: 0 for key in MEDIA_FILTER_DEFINITIONS}

    for story_filename in story_files:
        with open(join(stories_dir, story_filename), "r",
                  encoding="utf-8") as handle:
            story = load(handle)
        entry = classify_story_media(story, story_filename)
        stories.append(entry)
        for filter_key in entry["filters"]:
            buckets[filter_key].append(
                {
                    "story_id": entry["story_id"],
                    "title": entry["title"],
                    "slug": entry["slug"],
                    "sequence_number": entry["sequence_number"],
                    "media_items": entry["media_items"],
                }
            )
            filter_counts[filter_key] += 1

    stories_with_any = sum(1 for entry in stories if entry["filters"])
    stories_with_multiple = sum(1 for entry in stories if len(entry["filters"]) > 1)

    return {
        "summary": {
            "story_files": len(stories),
            "stories_with_classified_media": stories_with_any,
            "stories_with_multiple_media_types": stories_with_multiple,
            "filter_counts": filter_counts,
        },
        "definitions": MEDIA_FILTER_DEFINITIONS,
        "buckets": buckets,
        "stories": stories,
    }


def filter_stories(report, filter_keys):
    filter_keys = set(filter_keys)
    if not filter_keys:
        return report["stories"]
    return [
        entry
        for entry in report["stories"]
        if filter_keys.issubset(set(entry["filters"]))
    ]


def build_media_index(report):
    return {
        entry["story_id"]: entry["flags"]
        for entry in report["stories"]
    }


def render_media_types_constants():
    lines = [
        "/** Auto-generated by scripts/classify_story_media.py. Do not edit manually. */",
        "",
        'export type MediaTypeFilter = "thumbnail" | "gif" | "video_file" | "video_embed";',
        "",
        "export const MEDIA_TYPE_FILTERS: MediaTypeFilter[] = [",
    ]
    for key in MEDIA_FILTER_DEFINITIONS:
        lines.append(f'  "{key}",')
    lines.extend(
        [
            "];",
            "",
            "export const MEDIA_TYPE_LABELS: Record<MediaTypeFilter, string> = {",
        ]
    )
    for key, meta in MEDIA_FILTER_DEFINITIONS.items():
        lines.append(f'  {key}: "{meta["label"]}",')
    lines.extend(["};", ""])
    return "\n".join(lines)


def print_report(report):
    summary = report["summary"]
    print("Story media classification")
    print("=" * 72)
    print(f"Story files: {summary['story_files']:,}")
    print(f"Stories with classified media: {summary['stories_with_classified_media']:,}")
    print(f"Stories with multiple media types: {summary['stories_with_multiple_media_types']:,}")
    print()
    print("Filter counts:")
    for key, count in summary["filter_counts"].items():
        label = MEDIA_FILTER_DEFINITIONS[key]["label"]
        print(f"  {label} ({key}): {count:,}")
    print()
    for key in MEDIA_FILTER_DEFINITIONS:
        bucket = report["buckets"][key]
        if not bucket:
            continue
        label = MEDIA_FILTER_DEFINITIONS[key]["label"]
        print(f"{label} ({len(bucket):,}):")
        for entry in bucket[:10]:
            print(f"  {entry['story_id']}: {entry['title'][:70]}")
        if len(bucket) > 10:
            print(f"  ... and {len(bucket) - 10:,} more in report")
        print()


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(
        description="Classify storyblok_stories by thumbnail, GIF, and video media."
    )
    parser.add_argument(
        "--filter",
        action="append",
        choices=sorted(MEDIA_FILTER_DEFINITIONS),
        dest="filters",
        help="Print only stories matching all selected media filters.",
    )
    args = parser.parse_args()

    base_path = abspath(join(dirname(__file__), ".."))
    stories_dir = join(base_path, "data", "storyblok_stories")
    report_path = join(base_path, "data", "story_media_classification_report.json")
    index_path = join(base_path, "data", "story_media_index.json")
    constants_path = join(
        base_path,
        "storyblok-viewer",
        "src",
        "constants",
        "mediaTypes",
        "index.ts",
    )

    report = build_classification_report(stories_dir)
    print_report(report)

    with open(report_path, "w", encoding="utf-8", newline="\n") as handle:
        dump(report, handle, indent=2, ensure_ascii=False)

    with open(index_path, "w", encoding="utf-8", newline="\n") as handle:
        dump(build_media_index(report), handle, indent=2, ensure_ascii=False)

    makedirs(dirname(constants_path), exist_ok=True)
    with open(constants_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_media_types_constants())

    if args.filters:
        matched = filter_stories(report, args.filters)
        labels = ", ".join(MEDIA_FILTER_DEFINITIONS[key]["label"] for key in args.filters)
        print(f"Stories matching {labels} ({len(matched):,}):")
        for entry in matched:
            print(f"  {entry['story_id']}: {entry['title']}")

    print(f"Report exported to {report_path}")
    print(f"Index exported to {index_path}")
    print(f"Viewer constants exported to {constants_path}")
