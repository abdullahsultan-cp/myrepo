"""Extract unique Storyblok filter values and write TypeScript constants for the viewer app."""

from __future__ import annotations

import argparse
import json
from os.path import abspath, dirname, join
from pathlib import Path

SCRIPTS_DIR = abspath(dirname(__file__))
BASE_PATH = abspath(join(SCRIPTS_DIR, ".."))
DEFAULT_STORIES_DIR = join(BASE_PATH, "data", "storyblok_stories")
DEFAULT_OUTPUT_DIR = join(BASE_PATH, "storyblok-viewer", "src", "constants")

FILTER_DEFINITIONS = {
    "tags": {
        "folder": "tags",
        "export_name": "TAGS",
        "type_name": "Tag",
    },
    "authors": {
        "folder": "authors",
        "export_name": "AUTHORS",
        "type_name": "Author",
    },
    "publishers": {
        "folder": "publishers",
        "export_name": "PUBLISHERS",
        "type_name": "Publisher",
    },
    "contentWriters": {
        "folder": "contentWriters",
        "export_name": "CONTENT_WRITERS",
        "type_name": "ContentWriter",
    },
}


def collect_filter_values(stories_dir: Path) -> dict[str, set[str]]:
    tags: set[str] = set()
    authors: set[str] = set()
    publishers: set[str] = set()
    content_writers: set[str] = set()

    for story_path in sorted(stories_dir.glob("*.json")):
        with story_path.open(encoding="utf-8") as handle:
            story = json.load(handle)

        for tag in story.get("tag_list") or []:
            if isinstance(tag, str) and tag.strip():
                tags.add(tag.strip())

        content = story.get("content") or {}
        for tag_entry in content.get("tags") or []:
            label = tag_entry.get("label") if isinstance(tag_entry, dict) else None
            if isinstance(label, str) and label.strip():
                tags.add(label.strip())

        for key, target in (
            ("author", authors),
            ("publisher", publishers),
            ("content_writer", content_writers),
        ):
            person = content.get(key) or {}
            title = person.get("title") if isinstance(person, dict) else None
            if isinstance(title, str) and title.strip():
                target.add(title.strip())

    return {
        "tags": tags,
        "authors": authors,
        "publishers": publishers,
        "contentWriters": content_writers,
    }


def render_constants_module(export_name: str, type_name: str, values: list[str]) -> str:
    lines = [
        "/** Auto-generated by scripts/extract_storyblok_filter_constants.py. Do not edit manually. */",
        "",
        f"export const {export_name} = [",
    ]

    for value in values:
        lines.append(f"  {json.dumps(value)},")

    lines.extend(
        [
            "] as const;",
            "",
            f"export type {type_name} = (typeof {export_name})[number];",
            "",
        ]
    )
    return "\n".join(lines)


def write_constants(output_dir: Path, values_by_key: dict[str, set[str]]) -> dict[str, int]:
    counts: dict[str, int] = {}

    for key, definition in FILTER_DEFINITIONS.items():
        folder = output_dir / definition["folder"]
        folder.mkdir(parents=True, exist_ok=True)

        sorted_values = sorted(values_by_key[key], key=str.casefold)
        module_path = folder / "index.ts"
        module_path.write_text(
            render_constants_module(
                definition["export_name"],
                definition["type_name"],
                sorted_values,
            ),
            encoding="utf-8",
        )
        counts[key] = len(sorted_values)

    return counts


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Extract Storyblok filter constants for storyblok-viewer.",
    )
    parser.add_argument(
        "--stories-dir",
        default=DEFAULT_STORIES_DIR,
        help="Directory containing Storyblok story JSON files.",
    )
    parser.add_argument(
        "--output-dir",
        default=DEFAULT_OUTPUT_DIR,
        help="Directory where TypeScript constants will be written.",
    )
    args = parser.parse_args()

    stories_dir = Path(args.stories_dir)
    output_dir = Path(args.output_dir)

    if not stories_dir.is_dir():
        raise SystemExit(f"Stories directory not found: {stories_dir}")

    values_by_key = collect_filter_values(stories_dir)
    counts = write_constants(output_dir, values_by_key)

    print(f"Wrote constants to {output_dir}")
    for key, count in counts.items():
        print(f"  {key}: {count}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
